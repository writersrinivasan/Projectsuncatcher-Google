export function knowledgeChunks(): { id: string; topic: string; text: string }[] {
  const chunks: { id: string; topic: string; text: string }[] = [];
  const push = (topic: string, text: string) => chunks.push({ id: `kb-${chunks.length + 1}`, topic, text });

  push("poem", `The poem: "${poem.lines.join(" / ")}". ${poem.form}. Model: ${poem.model}. Chip: ${poem.chip}. Prompt: ${poem.prompt} ${poem.downlink}. ${poem.claim} Google: "${poem.googleQuote}" ${poem.alsoTried}`);
  poem.reading.forEach((r) => push("poem", `Line "${r.line}": ${r.meaning}`));
  Object.entries(mission).forEach(([k, v]) => push("mission", `${k}: ${v}`));
  stats.forEach((s) => push("stats", `${s.value}: ${s.label}`));
  poemJourney.forEach((s, i) => push("poem journey", `Step ${i + 1} ${s.title}: ${s.detail}`));
  architecture.forEach((a) => push("architecture", `${a.title}: ${a.detail}`));
  earthChallenges.forEach((c) => push("earth challenges", `${c.title} (${c.stat}): ${c.detail}`));
  spaceAdvantages.forEach((c) => push("space advantages", `${c.title}: ${c.detail}`));
  spaceChallenges.forEach((c) => push("space challenges", `${c.title}: ${c.detail}`));
  whyWorkflow.forEach((s, i) => push("why space workflow", `Step ${i + 1} ${s.title}: ${s.detail}`));
  timeline.forEach((t) => push("timeline", `${t.date}: ${t.title}: ${t.detail} [${t.status}]`));
  players.forEach((p) => push("companies", `${p.name} [status: ${p.status}] ${p.program}. Facts: ${p.facts.join("; ")}. Perspective (analysis): ${p.perspective}`));
  futureVision.forEach((f) => push("future", `${f.horizon} ${f.title}: ${f.points.join("; ")} (projection)`));
  glossary.forEach((g) => push("glossary", `${g.term}: ${g.def}`));
  return chunks;
}
